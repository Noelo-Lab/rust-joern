#!/usr/bin/env python3
"""Translate complete pinned Scala operator matches; never infer schema names.

Only this bounded match-table grammar is translated. Unknown cases, changed
sources, missing constants and unmapped CDT operations stop generation. CDT
binding/type resolution is deliberately not simulated by this translator.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "tests/reference/joern-4.0.150"

# Lexical adapter, not translated Scala: CDT has already classified tokens.
# A None means the current Rust parser has no corresponding expression token.
BINARY = {
    "multiply": "*",
    "divide": "/",
    "modulo": "%",
    "plus": "+",
    "minus": "-",
    "shiftLeft": "<<",
    "shiftRight": ">>",
    "lessThan": "<",
    "greaterThan": ">",
    "lessEqual": "<=",
    "greaterEqual": ">=",
    "binaryAnd": "&",
    "binaryXor": "^",
    "binaryOr": "|",
    "logicalAnd": "&&",
    "logicalOr": "||",
    "assign": "=",
    "multiplyAssign": "*=",
    "divideAssign": "/=",
    "moduloAssign": "%=",
    "plusAssign": "+=",
    "minusAssign": "-=",
    "shiftLeftAssign": "<<=",
    "shiftRightAssign": ">>=",
    "binaryAndAssign": "&=",
    "binaryXorAssign": "^=",
    "binaryOrAssign": "|=",
    "equals": "==",
    "notequals": "!=",
    "pmdot": ".*",
    "pmarrow": "->*",
    "max": None,
    "min": None,
    # A GNU case range is parsed as a binary expression.
    "ellipses": "...",
}
UNARY = {
    "prefixIncr": ("++", False),
    "prefixDecr": ("--", False),
    "plus": ("+", None),
    "minus": ("-", None),
    "star": ("*", None),
    "amper": ("&", None),
    "tilde": ("~", None),
    "not": ("!", None),
    "sizeof": ("sizeof", None),
    "postFixIncr": ("++", True),
    "postFixDecr": ("--", True),
    "typeid": ("typeid", None),
    # Parentheses have a separate AST owner; they are not a unary token.
    "bracketedPrimary": None,
}


def extract_match(source: str, start: str, enum: str) -> list[tuple[str, str]]:
    if source.count(start) != 1:
        raise ValueError(f"expected one complete match: {start}")
    body = source.split(start, 1)[1].split("}", 1)[0]
    pattern = re.compile(
        rf"\s*case (?:{enum}\.op_(\w+)|(_))\s*=>\s*((?:Operators|Defines)\.\w+)\s*"
    )
    result = []
    for line in body.splitlines():
        if not line.strip():
            continue
        match = pattern.fullmatch(line)
        if not match:
            raise ValueError(f"untranslated Scala branch: {line!r}")
        operation = match[1] or match[2]
        if operation in dict(result):
            raise ValueError(f"duplicate branch: {operation}")
        result.append((operation, match[3]))
    if not result or result[-1][0] != "_":
        raise ValueError("missing terminal fallback")
    return result


def generate(reference: Path = REFERENCE) -> str:
    manifest = json.loads((reference / "manifest.json").read_text())
    if manifest["commit"] != "958fdd3d976197a783f8ade1254b43e977648f28":
        raise ValueError("review a new upstream version before regenerating")
    for name, digest in manifest["files"].items():
        if hashlib.sha256((reference / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"changed reference: {name}")
    source = (reference / "AstForExpressionsCreator.scala").read_text()
    defines = dict(
        re.findall(
            r'val (\w+)\s*=\s*"([^"\n]*)"', (reference / "Defines.scala").read_text()
        )
    )
    operators = manifest["constants"][
        "io.shiftleft.codepropertygraph.generated.Operators"
    ]

    def value(symbol: str) -> str:
        owner, name = symbol.split(".")
        return json.dumps((operators if owner == "Operators" else defines)[name])

    tables = [
        (
            "binary_operator",
            "val op = bin.getOperator match {",
            "IASTBinaryExpression",
            BINARY,
        ),
        (
            "unary_operator",
            "val operatorMethod = unary.getOperator match {",
            "IASTUnaryExpression",
            UNARY,
        ),
    ]
    lines = [
        "// @generated by scripts/joern_port/generate_operators.py; do not edit.",
        "// Derived from Joern v4.0.150, commit " + manifest["commit"] + ".",
        "// Apache-2.0; source, license and JVM constants: tests/reference/joern-4.0.150/.",
        "// This ports operator selection, not CDT parsing, binding or type inference.",
        "",
    ]
    for name, marker, enum, tokens in tables:
        branches = extract_match(source, marker, enum)
        if set(dict(branches)) != set(tokens) | {"_"}:
            raise ValueError(f"incomplete lexical adapter: {enum}")
        cdt = manifest["constants"]["org.eclipse.cdt.core.dom.ast." + enum]
        if any("op_" + op not in cdt for op in tokens):
            raise ValueError(f"operation absent from installed CDT: {enum}")
        unary = name.startswith("unary")
        args = "operator: &str, postfix: bool" if unary else "operator: &str"
        lines += [
            f"pub(crate) fn {name}({args}) -> &'static str {{",
            "    match (operator, postfix) {" if unary else "    match operator {",
        ]
        for operation, symbol in branches[:-1]:
            token = tokens[operation]
            if token is None:
                lines.append(
                    f"        // {enum}.op_{operation}: separate/unsupported parser owner."
                )
                continue
            if unary:
                spelling, postfix = token
                flag = "_" if postfix is None else str(postfix).lower()
                key = f"({json.dumps(spelling)}, {flag})"
            else:
                key = json.dumps(token)
            lines.append(f"        {key} => {value(symbol)},")
        lines += [f"        _ => {value(branches[-1][1])},", "    }", "}", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "src/joern_operators.rs")
    args = parser.parse_args()
    # rustfmt is the repository's canonical formatter, including generated code.
    import subprocess

    formatted = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=generate(),
        text=True,
        capture_output=True,
        check=True,
    ).stdout
    if args.check:
        if args.output.read_text() != formatted:
            print("generated operator port is stale", file=sys.stderr)
            return 1
    else:
        args.output.write_text(formatted)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
