#!/usr/bin/env python3
"""Record every O0/O2 CFG and usage difference from a complete corpus manifest.

Inputs are generated by inventory_decbench.py, capture_pyjoern_corpus.py and
check_decbench_usage.py. Comparisons require identical prepared bytes and exact
directed topology, node roles, function coverage and prototype classification.
No graph-size-only success or tolerated divergence is supported.
"""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from concurrent.futures import ProcessPoolExecutor, as_completed
import csv
from functools import lru_cache
import gzip
import hashlib
import json
import math
import multiprocessing as mp
import os
from pathlib import Path
import statistics
import time

from compare_pyjoern import compare


@lru_cache(maxsize=32)
def read_json(path: str) -> dict:
    return json.loads(Path(path).read_text())


def cfg_option_contract(options: object) -> str:
    """Validate recorded flags without inferring old preprocessed support."""
    if (isinstance(options, dict) and options.get("strict") is True
            and options.get("data_flow") is False):
        if set(options) == {"strict", "data_flow"}:
            return "historical_cfg_only"
        if (set(options) == {"strict", "data_flow", "preprocessed"}
                and options["preprocessed"] is True):
            return "preprocessed_cfg_only"
    raise ValueError("Candidate did not request an exact supported strict CFG-only profile")


def compare_case(case: dict, candidates: str) -> tuple[dict, list[dict]]:
    progress_dir = os.environ.get("RUST_JOERN_COMPARE_PROGRESS")
    def progress(function=None):
        if progress_dir:
            path = Path(progress_dir) / f"{os.getpid()}.json"
            path.write_text(json.dumps({"case": case["id"], "function": function,
                                        "started": time.time()}))
    progress()
    result = {key: case[key] for key in ("id", "optimization", "project", "kind", "source")}
    result.update(metric_excluded=case.get("metric_excluded"),
                  source_sha256=case.get("source_sha256"),
                  prepared_sha256=case.get("prepared_sha256"),
                  prepared_bytes=case.get("prepared_bytes"),
                  input_preparation_seconds=case.get("preparation_seconds"),
                  reference=case.get("reference"),
                  reference_origin=case.get("reference_origin"))
    if case.get("preparation_error"):
        return result | {"status": "preparation_error", "error": case["preparation_error"]}, []
    reference_path = Path(case["reference"])
    candidate_path = Path(candidates) / (case["id"] + ".json")
    result["candidate"] = str(candidate_path)
    try:
        if not reference_path.exists():
            error_path = Path(str(reference_path) + ".error.json")
            error = read_json(str(error_path)) if error_path.exists() else {"error": "Reference capture incomplete"}
            return result | {"status": "reference_error", "error": error.get("error")}, []
        if not candidate_path.exists():
            return result | {"status": "candidate_missing", "error": "Candidate extraction incomplete"}, []
        reference = read_json(str(reference_path))
        candidate = read_json(str(candidate_path))
        digest = case["prepared_sha256"]
        if reference.get("prepared_sha256", reference.get("source_sha256")) != digest:
            raise ValueError("Reference prepared input hash differs")
        if candidate.get("prepared_sha256") != digest:
            raise ValueError("Candidate prepared input hash differs")
        if not candidate.get("prepared_matches_manifest"):
            raise ValueError("Candidate extraction preparation was not verified")
        result["requested_option_contract"] = "invalid"
        result["requested_option_contract"] = cfg_option_contract(candidate.get("requested_options"))
        generation_path = Path(candidates) / "summary.json"
        if generation_path.exists():
            generation = read_json(str(generation_path))
            if candidate.get("native_library_sha256") != generation["native_library"]["sha256"]:
                raise ValueError("Candidate native library differs from the recorded generation")
        result.update(reference_generator=reference["generator"],
                      reference_seconds=reference.get("seconds"),
                      reference_timing_id=str(reference_path),
                      reference_timing_kind=reference.get("timing_kind"),
                      usage_status=candidate["status"],
                      usage_error=candidate.get("error"),
                      diagnostics=candidate.get("diagnostics", []),
                      timings=candidate.get("timings", {}),
                      fallback_timings=candidate.get("fallback_timings"),
                      candidate_module=candidate.get("pyjoern_module"),
                      native_library_sha256=candidate.get("native_library_sha256"),
                      requested_options=candidate.get("requested_options"),
                      reference_functions=len(reference["functions"]),
                      candidate_functions=len(candidate.get("functions", {})))
        rows = compare(reference["functions"], candidate.get("functions", {}), progress=progress)
        statuses = Counter(row["status"] for row in rows)
        bodies = Counter(row["status"] for row in rows
                         if row.get("reference", {}).get("degenerate") is False)
        declarations = Counter(row["status"] for row in rows
                               if row.get("reference", {}).get("degenerate") is True)
        result.update(function_statuses=dict(statuses), cfg_matched=statuses["match"],
                      non_degenerate_function_statuses=dict(bodies),
                      degenerate_function_statuses=dict(declarations),
                      cfg_divergent=sum(count for key, count in statuses.items() if key != "match"),
                      empty_reference=not reference["functions"],
                      topology_status="match" if all(row["status"] == "match" for row in rows) else "divergent")
        result["status"] = ("usage_error" if candidate["status"] != "ok"
                            else "diagnostics" if candidate.get("diagnostics")
                            else result["topology_status"])
        for row in rows:
            row["case"] = case["id"]
        return result, rows
    except (OSError, ValueError, KeyError) as error:
        return result | {"status": "comparison_error", "error": str(error)}, []


def timing_stats(values: list[float]) -> dict:
    if not values:
        return {"observations": 0, "total_seconds": 0, "median_seconds": None,
                "p95_seconds": None, "max_seconds": None}
    values.sort()
    return {"observations": len(values), "total_seconds": sum(values),
            "median_seconds": statistics.median(values),
            "p95_seconds": values[math.ceil(len(values) * .95) - 1],
            "max_seconds": values[-1]}


def measure(rows: list[dict], field: str = "timings") -> dict:
    values = defaultdict(list)
    for row in rows:
        for key, value in (row.get(field) or {}).items():
            if isinstance(value, (int, float)) and value >= 0:
                values[key].append(value)
    return {key: timing_stats(items) for key, items in values.items()}


def summarize(files: list[dict], manifest: dict, wall_seconds: float) -> dict:
    groups = {}
    for opt in ("O0", "O2"):
        for kind in ("source", "ida", "kuna"):
            selected = [row for row in files if row["optimization"] == opt and row["kind"] == kind]
            function_statuses = Counter()
            bodies, declarations = Counter(), Counter()
            times, fallback_times = defaultdict(list), defaultdict(list)
            reference_times = {}
            for row in selected:
                function_statuses.update(row.get("function_statuses", {}))
                bodies.update(row.get("non_degenerate_function_statuses", {}))
                declarations.update(row.get("degenerate_function_statuses", {}))
                for key, value in row.get("timings", {}).items():
                    if isinstance(value, (int, float)) and value >= 0:
                        times[key].append(value)
                for key, value in (row.get("fallback_timings") or {}).items():
                    if isinstance(value, (int, float)) and value >= 0:
                        fallback_times[key].append(value)
                if row.get("reference_seconds") is not None:
                    reference_times[row["reference_timing_id"]] = row["reference_seconds"]
            groups[f"{opt}/{kind}"] = {
                "files": len(selected), "file_statuses": dict(Counter(row["status"] for row in selected)),
                "usage_statuses": dict(Counter(row.get("usage_status", "unavailable") for row in selected)),
                "requested_option_contracts": dict(Counter(row.get("requested_option_contract", "unavailable") for row in selected)),
                "function_statuses": dict(function_statuses),
                "non_degenerate_function_statuses": dict(bodies),
                "degenerate_function_statuses": dict(declarations),
                "files_with_diagnostics": sum(bool(row.get("diagnostics")) for row in selected),
                "metric_excluded_files": sum(bool(row.get("metric_excluded")) for row in selected),
                "candidate_timing": {key: timing_stats(values) for key, values in times.items()},
                "successful_usage_timing": measure([row for row in selected if row.get("usage_status") == "ok"]),
                "failed_strict_timing": measure([row for row in selected if row.get("usage_status") != "ok"]),
                "parity_matched_timing": measure([row for row in selected if row["status"] == "match"]),
                "fallback_timing": {key: timing_stats(values) for key, values in fallback_times.items()},
                "reference_timing_unique_inputs": timing_stats(list(reference_times.values())),
            }
    expected_ids = [case["id"] for case in manifest["cases"]]
    recorded_ids = [row["id"] for row in files]
    input_errors = {"preparation_error", "reference_error", "candidate_missing", "comparison_error"}
    accounted = (len(expected_ids) == len(set(expected_ids)) == len(recorded_ids)
                 == len(set(recorded_ids)) and set(expected_ids) == set(recorded_ids))
    totals, bodies, declarations = Counter(), Counter(), Counter()
    for row in files:
        totals.update(row.get("function_statuses", {}))
        bodies.update(row.get("non_degenerate_function_statuses", {}))
        declarations.update(row.get("degenerate_function_statuses", {}))
    return {
        "schema_version": 1, "results_root": manifest["results_root"], "scope": manifest["scope"],
        "files_expected": len(manifest["cases"]), "files_recorded": len(files),
        "file_statuses": dict(Counter(row["status"] for row in files)),
        "requested_option_contracts": dict(Counter(row.get("requested_option_contract", "unavailable") for row in files)),
        "all_inputs_accounted_for": accounted,
        "all_graph_comparisons_completed": accounted and not any(row["status"] in input_errors for row in files),
        "unresolved_input_errors": dict(Counter(row["status"] for row in files if row["status"] in input_errors)),
        "function_statuses": dict(totals),
        "non_degenerate_function_statuses": dict(bodies),
        "degenerate_function_statuses": dict(declarations),
        "empty_reference_files": sum(bool(row.get("empty_reference")) for row in files),
        "candidate_timing": measure(files),
        "fallback_timing": measure(files, "fallback_timings"),
        "successful_usage_timing": measure([row for row in files if row.get("usage_status") == "ok"]),
        "failed_strict_timing": measure([row for row in files if row.get("usage_status") != "ok"]),
        "parity_matched_timing": measure([row for row in files if row["status"] == "match"]),
        "timing_percentile_method": "nearest rank: sorted_values[ceil(0.95 * observations) - 1]",
        "comparison_wall_seconds": wall_seconds, "groups": groups,
        "timing_notes": [
            "Native times include the C ABI analysis, JSON serialization and Python JSON decoding; CFG-only disables data flow but also constructs CPG.",
            "Python graph materialization and exact DecBench end-to-end extraction are timed separately.",
            "Failed strict usage and permissive fallback timings are recorded separately; fallback graphs are never reported as successful default usage.",
            "successful_usage_timing includes successful strict extractions even if their CFGs diverge; parity_matched_timing includes only fully matching files.",
            "Historical source cache has no CFG generation timing or parser version; missing measurements remain null.",
            "Historical two-field candidate options record strict CFG-only extraction; only the new three-field contract explicitly requests preprocessed=True.",
            "Fresh oracle timing measures isolated original CFG-only parse_source including JVM startup, DOT export and lifting.",
            "Repeated identical oracle inputs share one capture; reference timing totals count unique captures within each group.",
            "Concurrent wall times are observations under the recorded worker configuration, not single-thread microbenchmarks.",
        ],
        "parity_criteria": ["function coverage", "directed graph isomorphism",
                            "entry and exit roles", "DecBench source degeneracy", "same prepared input SHA-256"],
        "tolerated_divergences": [],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--candidates", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=8)
    args = parser.parse_args()
    manifest = json.loads(args.manifest.read_text())
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    (output / "progress").mkdir(exist_ok=True)
    os.environ["RUST_JOERN_COMPARE_PROGRESS"] = str(output / "progress")
    files, divergences = [], Counter()
    started = time.perf_counter()
    with gzip.open(output / "functions.jsonl.gz", "wt") as function_file, \
         gzip.open(output / "divergences.jsonl.gz", "wt") as divergence_file, \
         ProcessPoolExecutor(max_workers=args.workers, mp_context=mp.get_context("spawn")) as pool:
        futures = {pool.submit(compare_case, case, str(args.candidates.resolve())): case for case in manifest["cases"]}
        for done, future in enumerate(as_completed(futures), 1):
            row, functions = future.result()
            files.append(row)
            for function in functions:
                function_file.write(json.dumps(function, separators=(",", ":")) + "\n")
                if function["status"] != "match":
                    divergence_file.write(json.dumps(function | {"source": row["source"],
                        "prepared_sha256": row["prepared_sha256"], "reference_file": row["reference"],
                        "candidate_file": row["candidate"]}, separators=(",", ":")) + "\n")
                    divergences[function["status"]] += 1
            if row["status"] not in ("match", "divergent"):
                divergence_file.write(json.dumps({"case": row["id"], "status": row["status"],
                    "source": row["source"], "error": row.get("error") or row.get("usage_error"),
                    "diagnostics": row.get("diagnostics", []), "reference": row.get("reference"),
                    "candidate": row.get("candidate")}, separators=(",", ":")) + "\n")
            if done % 500 == 0 or done == len(futures):
                print(f"Compared {done}/{len(futures)} files; CFG differences {dict(divergences)}", flush=True)
    files.sort(key=lambda row: row["id"])
    with gzip.open(output / "files.jsonl.gz", "wt") as handle:
        for row in files:
            handle.write(json.dumps(row, separators=(",", ":")) + "\n")
    fields = ["id", "optimization", "project", "kind", "status", "usage_status",
              "reference_functions", "candidate_functions", "cfg_matched", "cfg_divergent",
              "prepared_bytes", "prepared_sha256", "reference_seconds", "input_preparation_seconds"]
    timing_fields = sorted({key for row in files for key in row.get("timings", {})})
    fallback_fields = sorted({"fallback_" + key for row in files
                              for key in (row.get("fallback_timings") or {})})
    with (output / "files.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields + timing_fields + fallback_fields)
        writer.writeheader()
        for row in files:
            writer.writerow({**{key: row.get(key) for key in fields}, **row.get("timings", {}),
                             **{"fallback_" + key: value for key, value in
                                (row.get("fallback_timings") or {}).items()}})
    summary = summarize(files, manifest, time.perf_counter() - started)
    try:
        import igraph
        summary["comparison_engine"] = {"name": "igraph BLISS (exact directed, role-colored)",
                                        "version": igraph.__version__}
    except ImportError:
        import networkx
        summary["comparison_engine"] = {"name": "NetworkX VF2++ (exact directed, role-colored)",
                                        "version": networkx.__version__}
    summary["candidate_generation"] = read_json(str(args.candidates / "summary.json")) if (args.candidates / "summary.json").exists() else None
    summary["oracle_capture"] = read_json(str(args.manifest.parent / "references/capture-summary.json")) if (args.manifest.parent / "references/capture-summary.json").exists() else None
    if summary["oracle_capture"]:
        summary["oracle_capture"].pop("inputs", None)
    if summary["candidate_generation"]:
        summary["candidate_generation"].pop("cases", None)
    core = sorted(Path(__file__).resolve().parents[1].joinpath("src").glob("*.rs"))
    summary["native_source_sha256"] = hashlib.sha256(b"".join(p.name.encode() + p.read_bytes() for p in core)).hexdigest()
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({"files": len(files), "statuses": summary["file_statuses"], "cfg_differences": dict(divergences)}), flush=True)
    return int(any(row["status"] != "match" for row in files))


if __name__ == "__main__":
    raise SystemExit(main())
